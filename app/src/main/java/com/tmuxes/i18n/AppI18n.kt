    fun translate(language: AppLanguage, message: String): String {
        if (message.isBlank()) return message
        return when (language) {
            AppLanguage.ZH_HANS -> zhHans[message] ?: translateDynamicZh(message) ?: message
            AppLanguage.EN,
            AppLanguage.SYSTEM -> message
        }
    }

    private fun translateDynamicZh(message: String): String? {
        fun match(pattern: String): MatchResult? = Regex(pattern).matchEntire(message)
        match("""Refresh (.+)""")?.let { return "刷新 ${it.groupValues[1]}" }
        match("""(.+) deleted""")?.let { return "${it.groupValues[1]} 已删除" }
        match("""Saved "(.+)"""")?.let { return "已保存 \"${it.groupValues[1]}\"" }
        match("""Saved to "(.+)"""")?.let { return "已保存到 \"${it.groupValues[1]}\"" }
        match("""Imported "(.+)"""")?.let { return "已导入 \"${it.groupValues[1]}\"" }
        match("""Type: (.+)""")?.let { return "类型：${it.groupValues[1]}" }
        match("""Created: (.+)""")?.let { return "创建时间：${it.groupValues[1]}" }
        match("""on (.+)""")?.let { return "位于 ${it.groupValues[1]}" }
        match("""Detach (.+)""")?.let { return "Detach ${it.groupValues[1]}" }
        match("""Delete (.+)\?""")?.let { return "删除 ${it.groupValues[1]}？" }
        match("""Delete "(.+)"\? This cannot be undone\.""")?.let {
            return "删除 \"${it.groupValues[1]}\"？此操作无法撤销。"
        }
        match("""Delete (.+) and all its snippets\? This cannot be undone\.""")?.let {
            return "删除 ${it.groupValues[1]} 及其所有片段？此操作无法撤销。"
        }
        match("""Delete (\d+) selected snippets?\? This cannot be undone\.""")?.let {
            return "删除已选择的 ${it.groupValues[1]} 个片段？此操作无法撤销。"
        }
        match("""Are you sure you want to delete "(.+)"\? This action cannot be undone\.""")?.let {
            return "确定要删除 \"${it.groupValues[1]}\"？此操作无法撤销。"
        }
        match("""Remove "(.+)" from trusted hosts\? You will be prompted to verify it again on next connection\.""")?.let {
            return "从可信主机中移除 \"${it.groupValues[1]}\"？下次连接时会再次要求验证。"
        }
        match("""Enter a new name for session '(.+)'\.""")?.let {
            return "输入会话 '${it.groupValues[1]}' 的新名称。"
        }
        match("""Kill session '(.+)'\? Running processes will be terminated\.""")?.let {
            return "结束会话 '${it.groupValues[1]}'？正在运行的进程将被终止。"
        }
        return null
    }
