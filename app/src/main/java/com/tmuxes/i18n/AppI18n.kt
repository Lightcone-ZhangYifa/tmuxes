package com.tmuxes.i18n

import androidx.compose.runtime.Composable
import androidx.compose.runtime.Immutable
import androidx.compose.runtime.staticCompositionLocalOf
import java.util.Locale

enum class AppLanguage(
    val settingValue: String,
    val displayName: String,
    val nativeName: String
) {
    SYSTEM("system", "System language", "跟随系统语言"),
    EN("en", "English", "English"),
    ZH_HANS("zh-Hans", "Simplified Chinese", "简体中文");

    companion object {
        fun fromSetting(value: String): AppLanguage =
            entries.firstOrNull { it.settingValue == value } ?: SYSTEM

        fun resolve(value: String): AppLanguage {
            val selected = fromSetting(value)
            if (selected != SYSTEM) return selected
            return when (Locale.getDefault().language.lowercase(Locale.ROOT)) {
                "zh" -> ZH_HANS
                else -> EN
            }
        }
    }
}

@Immutable
class I18n(private val language: AppLanguage) {
    fun t(message: String): String = I18nCatalog.translate(language, message)

    fun t(message: String, args: Map<String, Any?>): String {
        var text = t(message)
        for ((key, value) in args) {
            text = text.replace("{$key}", value?.toString().orEmpty())
        }
        return text
    }
}

val LocalI18n = staticCompositionLocalOf { I18n(AppLanguage.resolve(AppLanguage.SYSTEM.settingValue)) }

@Composable
fun t(message: String): String = LocalI18n.current.t(message)

@Composable
fun t(message: String, vararg args: Pair<String, Any?>): String =
    LocalI18n.current.t(message, args.toMap())

object I18nRuntime {
    @Volatile
    private var current = I18n(AppLanguage.resolve(AppLanguage.SYSTEM.settingValue))

    fun setLanguage(settingValue: String) {
        current = I18n(AppLanguage.resolve(settingValue))
    }

    fun t(message: String): String = current.t(message)

    fun t(message: String, vararg args: Pair<String, Any?>): String =
        current.t(message, args.toMap())
}

